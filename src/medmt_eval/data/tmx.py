"""Parse EMEA TMX translation-memory files with alignment-quality filtering.

The EMEA corpus ships as TMX 1.4 generated by Uplug from pdftotext output.
The raw 364 K pairs contain alignment noise (duplicated boilerplate, degenerate
product-code entries, extreme length-ratio outliers).  This module streams the
TMX, applies a configurable filtering pass, and optionally down-samples to a
target evaluation-set size.
"""

from __future__ import annotations

import gzip
import hashlib
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Iterable, Sequence

from medmt_eval.schema import Segment

# Default filtering thresholds.
DEFAULT_MIN_LENGTH = 3           # Minimum character length for each side.
DEFAULT_MAX_LENGTH_RATIO = 3.0   # Max len(longer) / len(shorter).
DEFAULT_SAMPLE_SIZE: int | None = None  # None → keep all filtered pairs.


def _stream_tmx_pairs(
    path: str | Path,
    *,
    src_lang: str = "de",
    tgt_lang: str = "en",
) -> Iterable[tuple[str, str]]:
    """Yield (src_text, tgt_text) pairs from a (possibly gzipped) TMX file.

    Uses iterparse so the ~108 MB uncompressed DOM is never fully loaded.
    """
    open_fn = gzip.open if str(path).endswith(".gz") else open
    with open_fn(path, "rt", encoding="utf-8") as fh:
        for event, elem in ET.iterparse(fh, events=("end",)):
            if elem.tag != "tu":
                continue
            src_text: str | None = None
            tgt_text: str | None = None
            for tuv in elem.findall("tuv"):
                lang = tuv.get("{http://www.w3.org/XML/1998/namespace}lang", "")
                # The EMEA TMX uses bare two-letter codes ("de", "en").
                seg = tuv.find("seg")
                if seg is None or seg.text is None:
                    continue
                text = " ".join(seg.text.split())
                if lang == src_lang:
                    src_text = text
                elif lang == tgt_lang:
                    tgt_text = text
            if src_text is not None and tgt_text is not None:
                yield src_text, tgt_text
            elem.clear()  # Free memory for processed <tu> elements.


def _is_degenerate(src: str, tgt: str, min_length: int) -> bool:
    """Return True for empty, product-code-like, or identical-across-languages pairs."""
    if len(src.strip()) < min_length or len(tgt.strip()) < min_length:
        return True
    # Identical across languages (product codes, numbers, brand names alone).
    if src.strip().lower() == tgt.strip().lower():
        return True
    return False


def _is_length_ratio_outlier(src: str, tgt: str, max_ratio: float) -> bool:
    """Return True when the length ratio exceeds the threshold."""
    shorter = min(len(src), len(tgt))
    longer = max(len(src), len(tgt))
    if shorter == 0:
        return True
    return (longer / shorter) > max_ratio


def load_emea_from_tmx(
    path: str | Path,
    *,
    src_lang: str = "de",
    tgt_lang: str = "en",
    min_length: int = DEFAULT_MIN_LENGTH,
    max_length_ratio: float = DEFAULT_MAX_LENGTH_RATIO,
    sample_size: int | None = DEFAULT_SAMPLE_SIZE,
    seed: int = 13,
    domain: str = "emea",
) -> list[Segment]:
    """Load, de-duplicate, filter, and optionally down-sample EMEA segments.

    Parameters
    ----------
    path:
        Path to ``emea-de-en.tmx.gz`` (or uncompressed ``.tmx``).
    src_lang, tgt_lang:
        Language pair to extract (default DE→EN).
    min_length:
        Minimum character count per side; shorter pairs are dropped.
    max_length_ratio:
        Maximum allowed ratio of longer/shorter side.
    sample_size:
        If set, randomly sample this many segments after filtering.
        Uses deterministic ``seed`` for reproducibility.
    domain:
        Domain label for the emitted segments.
    """
    import random

    seen: set[str] = set()
    pairs: list[tuple[str, str]] = []

    for src_text, tgt_text in _stream_tmx_pairs(path, src_lang=src_lang, tgt_lang=tgt_lang):
        # Deduplicate by content hash.
        key = hashlib.sha256(f"{src_text}\t{tgt_text}".encode()).hexdigest()
        if key in seen:
            continue
        seen.add(key)
        # Filter degenerate and outlier pairs.
        if _is_degenerate(src_text, tgt_text, min_length):
            continue
        if _is_length_ratio_outlier(src_text, tgt_text, max_length_ratio):
            continue
        pairs.append((src_text, tgt_text))

    # Optional deterministic down-sampling.
    if sample_size is not None and sample_size < len(pairs):
        rng = random.Random(seed)
        pairs = rng.sample(pairs, sample_size)

    segments: list[Segment] = []
    for idx, (src_text, tgt_text) in enumerate(pairs, start=1):
        segments.append(
            Segment(
                id=f"emea-{idx:06d}",
                domain=domain,
                src_lang=src_lang,
                tgt_lang=tgt_lang,
                src_text=src_text,
                ref_text=tgt_text,
            )
        )
    return segments
